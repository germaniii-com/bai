const simpleBySlug = new Map();
for (const icon of Object.values(simpleIcons)) {
  if (icon && typeof icon === "object" && typeof icon.slug === "string") simpleBySlug.set(icon.slug, icon);
}
const logos = JSON.parse(readFileSync(new URL("../node_modules/@iconify-json/logos/icons.json", import.meta.url), "utf8"));

const icons = {};
const fallbacks = {};
const missing = [];

for (const entry of MCP_CATALOG) {
  const ref = REFS[entry.name];
  if (ref === undefined) {
    missing.push(`${entry.name} (no ref)`);
    continue;
  }
  const [set, key] = ref.split(":");
  if (set === "lucide") {
    fallbacks[entry.name] = key;
    continue;
  }
  if (set === "simple-icons") {
    const icon = simpleBySlug.get(key);
    if (icon === undefined) {
      missing.push(`${entry.name} → ${ref}`);
      continue;
    }
    icons[entry.name] = { viewBox: "0 0 24 24", body: `<path d="${icon.path}"/>` };
    continue;
  }
  if (set === "logos") {
    const icon = logos.icons[key];
    if (icon === undefined) {
      missing.push(`${entry.name} → ${ref}`);
      continue;
    }
    const width = icon.width ?? logos.width ?? 24;
    const height = icon.height ?? logos.height ?? 24;
    // Strip embedded hex fills so the icon inherits `currentColor` and reads as
    // a monochrome mark alongside the app's lucide UI icons.
    const body = icon.body.replace(/\sfill="#[0-9a-fA-F]{3,8}"/g, "");
    icons[entry.name] = { viewBox: `0 0 ${width} ${height}`, body };
    continue;
  }
  missing.push(`${entry.name} → unknown set ${set}`);
}

if (missing.length > 0) {
  console.error(`[generate-mcp-icons] unresolved:\n  ${missing.join("\n  ")}`);
  process.exit(1);
}

const out = `// AUTO-GENERATED by scripts/generate-mcp-icons.mjs — do not edit by hand.
// Source: simple-icons ∪ @iconify-json/logos (brand marks) + lucide fallbacks.
export interface McpBrandIcon {
  viewBox: string;
  body: string;
}

/** Brand SVG data keyed by MCP catalog entry name. */
export const MCP_ICONS: Record<string, McpBrandIcon> = ${JSON.stringify(icons, null, 2)};

/** Lucide icon name for entries with no brand mark. */
export const MCP_FALLBACKS: Record<string, string> = ${JSON.stringify(fallbacks, null, 2)};
`;

writeFileSync(new URL("../src/mcp-icons.ts", import.meta.url), out);
console.log(`[generate-mcp-icons] wrote ${Object.keys(icons).length} brand icons, ${Object.keys(fallbacks).length} lucide fallbacks`);
