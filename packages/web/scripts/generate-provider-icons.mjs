/**
 * Compiles the model-provider brand marks into a small static map
 * (`src/provider-icons.ts`), so the app ships only the ~40 icons it uses
 * instead of the multi-megabyte icon packs — the same approach as
 * `generate-mcp-icons.mjs`.
 *
 * Sources: `simple-icons` ∪ `@iconify-json/logos` (brand marks), with lucide
 * fallbacks for brands neither pack carries. Icons render monochrome
 * (`currentColor`) to match the app's lucide UI icons.
 *
 * Run: `bun run generate:provider-icons` (from packages/web).
 */
import { readFileSync, writeFileSync } from "node:fs";
import * as simpleIcons from "simple-icons";

/** canonical key → "simple-icons:<slug>" | "logos:<name>" | "lucide:<IconName>". */
const REFS = {
  openai: "logos:openai-icon",
  anthropic: "simple-icons:anthropic",
  claude: "simple-icons:claude",
  google: "simple-icons:google",
  gemini: "simple-icons:googlegemini",
  vertex: "simple-icons:googlecloud",
  xai: "simple-icons:x",
  groq: "lucide:Zap",
  mistral: "simple-icons:mistralai",
  deepseek: "simple-icons:deepseek",
  meta: "simple-icons:meta",
  openrouter: "simple-icons:openrouter",
  ollama: "simple-icons:ollama",
  cohere: "lucide:Orbit",
  azure: "logos:microsoft-azure",
  microsoft: "logos:microsoft",
  copilot: "simple-icons:githubcopilot",
  aws: "logos:aws",
  nvidia: "simple-icons:nvidia",
  moonshot: "simple-icons:moonshotai",
  qwen: "simple-icons:qwen",
  alibaba: "simple-icons:alibabacloud",
  zhipu: "lucide:Sparkles",
  minimax: "simple-icons:minimax",
  baidu: "simple-icons:baidu",
  github: "simple-icons:github",
  huggingface: "simple-icons:huggingface",
  perplexity: "simple-icons:perplexity",
  together: "lucide:Layers",
  fireworks: "lucide:Flame",
  cerebras: "lucide:Cpu",
  lmstudio: "simple-icons:lmstudio",
  opencode: "simple-icons:opencode",
  upstage: "lucide:Bot",
  xiaomi: "simple-icons:xiaomi",
  voyage: "lucide:Compass",
  jina: "lucide:Search",
  ai21: "lucide:Bot",
  reka: "lucide:Bot",
  nous: "lucide:Bot",
  cloudflare: "simple-icons:cloudflare",
  generic: "lucide:Cloud",
};

const simpleBySlug = new Map();
for (const icon of Object.values(simpleIcons)) {
  if (icon && typeof icon === "object" && typeof icon.slug === "string") simpleBySlug.set(icon.slug, icon);
}
const logos = JSON.parse(readFileSync(new URL("../node_modules/@iconify-json/logos/icons.json", import.meta.url), "utf8"));

const icons = {};
const fallbacks = {};

for (const [key, ref] of Object.entries(REFS)) {
  const [set, name] = ref.split(":");
  if (set === "lucide") {
    fallbacks[key] = name;
    continue;
  }
  if (set === "simple-icons") {
    const icon = simpleBySlug.get(name);
    if (icon === undefined) {
      console.warn(`[generate-provider-icons] missing simple-icons:${name} for "${key}" (falling back)`);
      fallbacks[key] = "Cloud";
      continue;
    }
    icons[key] = { viewBox: "0 0 24 24", body: `<path d="${icon.path}"/>` };
    continue;
  }
  if (set === "logos") {
    const icon = logos.icons[name];
    if (icon === undefined) {
      console.warn(`[generate-provider-icons] missing logos:${name} for "${key}" (falling back)`);
      fallbacks[key] = "Cloud";
      continue;
    }
    const width = icon.width ?? logos.width ?? 24;
    const height = icon.height ?? logos.height ?? 24;
    // Strip embedded hex fills so the mark inherits `currentColor`.
    const body = icon.body.replace(/\sfill="#[0-9a-fA-F]{3,8}"/g, "");
    icons[key] = { viewBox: `0 0 ${width} ${height}`, body };
    continue;
  }
  console.warn(`[generate-provider-icons] unknown set "${set}" for "${key}"`);
}

const out = `// AUTO-GENERATED by scripts/generate-provider-icons.mjs — do not edit by hand.
// Source: simple-icons ∪ @iconify-json/logos (brand marks) + lucide fallbacks.
export interface ProviderBrandIcon {
  viewBox: string;
  body: string;
}

/** Brand SVG data keyed by canonical provider key. */
export const PROVIDER_ICONS: Record<string, ProviderBrandIcon> = ${JSON.stringify(icons, null, 2)};

/** Lucide icon name for keys with no brand mark. */
export const PROVIDER_FALLBACKS: Record<string, string> = ${JSON.stringify(fallbacks, null, 2)};
`;

writeFileSync(new URL("../src/provider-icons.ts", import.meta.url), out);
console.log(
  `[generate-provider-icons] wrote ${Object.keys(icons).length} brand icons, ${Object.keys(fallbacks).length} lucide fallbacks`,
);
